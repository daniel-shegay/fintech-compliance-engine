// ── Про charge ──────────────────────────────────────────────────────────────
// Остаток Cena читается из l_interest, а НЕ из r_charge, хотя в writeoff
// уходит полем charge. Лейбл столбца у вендора кривой, и это подтверждено
// тестовыми проводками по реальному займу (2026-09-03):
//
//   до отписа        debt 7470.26   r_charge 500.00   (l_interest тоже 500.00)
//   отписали         charge 500.00  -> система приняла, debt упал на все 5000
//   после отписа     debt 2470.26 = l_amount, а r_charge ВСЁ ЕЩЁ 500.00
//
// То есть r_charge при отписе не уменьшается — это начисленная сумма, а не
// остаток. Второе подтверждение из другого кредита (1026701): r_charge
// 24000.00 при debt 22834.66, остаток не может превышать долг.
//
// Ловушка: пока по Cena ничего не погашено, l_interest и r_charge равны,
// сумма корзин сходится с debt и подмена столбца никак не проявляется.
// Расхождение вылезает только после первого частичного погашения.
// ────────────────────────────────────────────────────────────────────────────

